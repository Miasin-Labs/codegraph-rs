use super::{
    AnalyzeCommands,
    MiriArgs,
    RuleSources,
    ScoreArgs,
    cmd_analyze_boundaries,
    cmd_analyze_bugs,
    cmd_analyze_capabilities,
    cmd_analyze_centrality,
    cmd_analyze_cfg,
    cmd_analyze_co_change,
    cmd_analyze_communities,
    cmd_analyze_complexity,
    cmd_analyze_coverage,
    cmd_analyze_critical,
    cmd_analyze_cycles,
    cmd_analyze_dataflow,
    cmd_analyze_diff,
    cmd_analyze_dominators,
    cmd_analyze_export,
    cmd_analyze_fuzz_harness,
    cmd_analyze_fuzz_run,
    cmd_analyze_fuzz_targets,
    cmd_analyze_generics,
    cmd_analyze_impact,
    cmd_analyze_miri,
    cmd_analyze_query,
    cmd_analyze_review,
    cmd_analyze_risk,
    cmd_analyze_rules,
    cmd_analyze_schema,
    cmd_analyze_slice,
    cmd_analyze_stats,
    cmd_analyze_taint,
    cmd_analyze_traits,
    cmd_analyze_types,
    cmd_analyze_validate,
};

/// codegraph analyze <subcommand>
pub(crate) fn cmd_analyze(command: AnalyzeCommands) {
    match command {
        AnalyzeCommands::Query {
            query,
            path,
            max_nodes,
            why,
            explain,
            lcov,
            no_cache,
            json,
        } => cmd_analyze_query(
            &query,
            path.as_deref(),
            &max_nodes,
            why,
            explain,
            lcov.as_deref(),
            no_cache,
            json,
        ),
        AnalyzeCommands::Complexity {
            path,
            top,
            no_cache,
            json,
        } => cmd_analyze_complexity(path.as_deref(), &top, no_cache, json),
        AnalyzeCommands::Communities {
            path,
            sample,
            no_cache,
            json,
        } => cmd_analyze_communities(path.as_deref(), &sample, no_cache, json),
        AnalyzeCommands::Dominators {
            symbol,
            path,
            top,
            no_cache,
            json,
        } => cmd_analyze_dominators(&symbol, path.as_deref(), &top, no_cache, json),
        AnalyzeCommands::Slice {
            symbol,
            direction,
            path,
            depth,
            value_level,
            source_annotated,
            no_cache,
            json,
        } => cmd_analyze_slice(
            &symbol,
            &direction,
            path.as_deref(),
            &depth,
            value_level,
            source_annotated,
            no_cache,
            json,
        ),
        AnalyzeCommands::Cycles {
            path,
            no_cache,
            json,
        } => cmd_analyze_cycles(path.as_deref(), no_cache, json),
        AnalyzeCommands::Impact {
            symbol,
            signature,
            path,
            no_cache,
            json,
        } => cmd_analyze_impact(
            &symbol,
            signature.as_deref(),
            path.as_deref(),
            no_cache,
            json,
        ),
        AnalyzeCommands::Taint {
            source,
            sink,
            suggest,
            value_level,
            source_annotated,
            path,
            max_nodes,
            top,
            no_cache,
            json,
        } => cmd_analyze_taint(
            source.as_deref(),
            sink.as_deref(),
            suggest,
            value_level,
            source_annotated,
            path.as_deref(),
            &max_nodes,
            &top,
            no_cache,
            json,
        ),
        AnalyzeCommands::CoChange {
            symbol,
            min_support,
            max_commits,
            top,
            path,
            no_cache,
            json,
        } => cmd_analyze_co_change(
            symbol.as_deref(),
            &min_support,
            &max_commits,
            &top,
            path.as_deref(),
            no_cache,
            json,
        ),
        AnalyzeCommands::Review {
            at,
            rule,
            base,
            detectors,
            compiler_wait,
            rules,
            rule_text,
            builtin,
            tests,
            top,
            path,
            json,
        } => cmd_analyze_review(
            at.as_deref(),
            rule,
            base.as_deref(),
            &detectors,
            compiler_wait.as_deref(),
            &RuleSources {
                paths: rules,
                texts: rule_text,
                builtin,
                saved: false,
            },
            tests,
            &top,
            path.as_deref(),
            json,
        ),
        AnalyzeCommands::Rules {
            paths,
            rules,
            rule_text,
            builtin,
            no_saved,
            check,
            score,
            sample,
            seed,
            slack,
            work,
            jobs,
            deadline,
            cursor,
            base,
            tests,
            top,
            path,
            json,
        } => cmd_analyze_rules(
            &RuleSources {
                paths: paths.into_iter().chain(rules).collect(),
                texts: rule_text,
                builtin,
                saved: !no_saved,
            },
            check,
            score.map(|corpus| ScoreArgs {
                corpus,
                sample,
                seed,
                slack,
                work,
                jobs,
                deadline,
                cursor,
            }),
            base.as_deref(),
            tests,
            top.as_deref(),
            path.as_deref(),
            json,
        ),
        AnalyzeCommands::Bugs {
            base,
            detectors,
            compiler_wait,
            tests,
            no_ecosystem,
            top,
            path,
            json,
        } => cmd_analyze_bugs(
            base.as_deref(),
            &detectors,
            compiler_wait.as_deref(),
            tests,
            !no_ecosystem,
            top.as_deref(),
            path.as_deref(),
            json,
        ),
        AnalyzeCommands::FuzzTargets {
            finding,
            function,
            no_findings,
            top,
            path,
            json,
        } => cmd_analyze_fuzz_targets(
            finding.as_deref(),
            function.as_deref(),
            no_findings,
            &top,
            path.as_deref(),
            json,
        ),
        AnalyzeCommands::FuzzHarness {
            function,
            finding,
            out,
            force,
            dry_run,
            path,
            json,
        } => cmd_analyze_fuzz_harness(
            function.as_deref(),
            finding.as_deref(),
            out.as_deref(),
            force,
            dry_run,
            path.as_deref(),
            json,
        ),
        AnalyzeCommands::FuzzRun {
            target,
            seconds,
            input,
            fuzz_dir,
            sanitizer,
            build_timeout,
            path,
            json,
        } => cmd_analyze_fuzz_run(
            &target,
            &seconds,
            input.as_deref(),
            fuzz_dir.as_deref(),
            sanitizer,
            &build_timeout,
            path.as_deref(),
            json,
        ),
        AnalyzeCommands::Miri {
            finding,
            function,
            all_unsafe: _,
            seconds,
            build_timeout,
            max_tests,
            borrows,
            permissive_provenance,
            disable_isolation,
            ignore_leaks,
            miri_flag,
            online,
            target_dir,
            no_harness,
            dry_run,
            log,
            path,
            json,
        } => cmd_analyze_miri(MiriArgs {
            finding,
            function,
            seconds,
            build_timeout,
            max_tests,
            borrows,
            permissive_provenance,
            disable_isolation,
            ignore_leaks,
            miri_flag,
            online,
            target_dir,
            no_harness,
            dry_run,
            log,
            path,
            json,
        }),
        AnalyzeCommands::Risk {
            base,
            depth,
            test_depth,
            untested,
            top,
            path,
            json,
        } => cmd_analyze_risk(
            &base,
            &depth,
            &test_depth,
            untested,
            &top,
            path.as_deref(),
            json,
        ),
        AnalyzeCommands::Coverage {
            lcov,
            untested,
            top,
            path,
            no_cache,
            json,
        } => cmd_analyze_coverage(&lcov, untested, &top, path.as_deref(), no_cache, json),
        AnalyzeCommands::Validate {
            symbol,
            params_before,
            params_after,
            path,
            no_cache,
            json,
        } => cmd_analyze_validate(
            &symbol,
            &params_before,
            &params_after,
            path.as_deref(),
            no_cache,
            json,
        ),
        AnalyzeCommands::Traits {
            type_name,
            path,
            no_cache,
            json,
        } => cmd_analyze_traits(type_name.as_deref(), path.as_deref(), no_cache, json),
        AnalyzeCommands::Centrality {
            top,
            path,
            no_cache,
            json,
        } => cmd_analyze_centrality(&top, path.as_deref(), no_cache, json),
        AnalyzeCommands::Critical {
            top,
            path,
            no_cache,
            json,
        } => cmd_analyze_critical(&top, path.as_deref(), no_cache, json),
        AnalyzeCommands::Export {
            format,
            symbol,
            depth,
            path,
            no_cache,
            json,
        } => cmd_analyze_export(
            &format,
            symbol.as_deref(),
            &depth,
            path.as_deref(),
            no_cache,
            json,
        ),
        AnalyzeCommands::Types {
            symbol,
            path,
            no_cache,
            json,
        } => cmd_analyze_types(&symbol, path.as_deref(), no_cache, json),
        AnalyzeCommands::Generics {
            symbol,
            path,
            no_cache,
            json,
        } => cmd_analyze_generics(symbol.as_deref(), path.as_deref(), no_cache, json),
        AnalyzeCommands::Boundaries {
            path,
            no_cache,
            json,
        } => cmd_analyze_boundaries(path.as_deref(), no_cache, json),
        AnalyzeCommands::Capabilities { json } => cmd_analyze_capabilities(json),
        AnalyzeCommands::Schema { kind, json } => cmd_analyze_schema(&kind, json),
        AnalyzeCommands::Stats {
            estimate_reachability,
            top,
            path,
            no_cache,
            json,
        } => cmd_analyze_stats(estimate_reachability, &top, path.as_deref(), no_cache, json),
        AnalyzeCommands::Cfg {
            symbol,
            path,
            no_cache,
            json,
        } => cmd_analyze_cfg(&symbol, path.as_deref(), no_cache, json),
        AnalyzeCommands::Dataflow {
            symbol,
            path,
            no_cache,
            json,
        } => cmd_analyze_dataflow(&symbol, path.as_deref(), no_cache, json),
        AnalyzeCommands::Diff {
            base,
            depth,
            top,
            path,
            no_cache,
            json,
        } => cmd_analyze_diff(&base, &depth, &top, path.as_deref(), no_cache, json),
    }
}
