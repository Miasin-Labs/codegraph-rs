    fn cargo_toml_is_created_then_extended() {
        let manifest = cargo_toml("demo-codec", "..", &["decode"]);
        assert!(manifest.contains("[dependencies.demo-codec]\npath = \"..\"\n"));
        assert!(manifest.contains("[[bin]]\nname = \"decode\"\npath = \"fuzz_targets/decode.rs\""));
        assert_eq!(update_cargo_toml(&manifest, "decode", true), None);
        let updated = update_cargo_toml(&manifest, "parse", false).unwrap();
        assert!(updated.contains("name = \"parse\""));
        let bare = "[package]\nname = \"x-fuzz\"\n\n[dependencies]\nlibfuzzer-sys = \"0.4\"\n";
        let updated = update_cargo_toml(bare, "parse", true).unwrap();
        assert!(updated.contains("[dependencies]\narbitrary = { version = \"1\", features = [\"derive\"] }\nlibfuzzer-sys"));
    }
